SAMPLES_DIR = BACKEND_DIR / "assets" / "samples"
VOICE_DESIGN_DIR = SAMPLES_DIR / "voice_design"
DICTATION_DIR = SAMPLES_DIR / "dictation"

# Make `backend/` importable so we can pull personalities + the engine.
